test('a missed task can be rescheduled with a visible mark and original date preserved',async({page})=>{
  await page.getByRole('button',{name:'Добавить задачу',exact:true}).first().click();
  await page.getByLabel('Что нужно сделать?').fill('Перенести незавершённое дело');
  await page.getByLabel('Время начала').fill('00:00');
  await page.getByRole('button',{name:'Добавить задачу',exact:true}).last().click();
  await expect(page.getByText('Пропущена',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Перенести',exact:true}).first().click();
  await page.getByRole('button',{name:'Перенести задачу',exact:true}).click();
  await page.getByRole('button',{name:'Неделя',exact:true}).click();
  await expect(page.getByText('Перенесена',{exact:true}).first()).toBeVisible();
  const occurrence=await page.evaluate(()=>Object.values(JSON.parse(localStorage.getItem('vesper7:device')).occurrences)[0]);
  expect(occurrence.history).toHaveLength(1);expect(occurrence.history[0].type).toBe('rescheduled');expect(occurrence.originalDate).toBeTruthy();
});
test('time tracking saves elapsed time and cycle observations survive reload',async({page})=>{
  await page.clock.install();
  await page.getByRole('button',{name:'Добавить задачу',exact:true}).first().click();
  await page.getByLabel('Что нужно сделать?').fill('Фокус на теме');
  await page.getByRole('button',{name:'Добавить задачу',exact:true}).last().click();
  await page.getByRole('button',{name:'Начать',exact:true}).first().click();
  await page.clock.fastForward(65000);
  await page.getByRole('button',{name:'Сохранить время',exact:true}).click();
  await expect(page.getByText('Факт: 1 мин',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Дневник цикла',exact:true}).click();
  await page.getByLabel('Был половой акт').check();
  await page.getByLabel('Личная заметка').fill('Запись для проверки сохранения');
  await page.getByRole('button',{name:'Сохранить запись',exact:true}).click();
  await page.reload();
  await expect(page.getByLabel('Личная заметка')).toHaveValue('Запись для проверки сохранения');
  await expect(page.getByLabel('Был половой акт')).toBeChecked();
});
