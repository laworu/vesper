import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{
  await page.route('https://fonts.googleapis.com/**',route=>route.abort());
  await page.goto('/');
  await page.getByLabel('Как к тебе обращаться?').fill('Лена');
  await page.getByRole('button',{name:'Открыть мою вселенную'}).click();
});
test('goal, daily linked task, completion, reward undo and persistence',async({page})=>{
  await page.getByRole('button',{name:'Создать цель',exact:true}).first().click();
  await page.getByLabel('К какому результату хочешь прийти?').fill('Подготовиться к пробнику');
  await page.getByLabel('Учебная цель').check();
  await page.getByRole('button',{name:'Создать цель',exact:true}).last().click();
  await expect(page.getByRole('heading',{name:'Подготовиться к пробнику',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Добавить задачу',exact:true}).first().click();
  await page.getByLabel('Что нужно сделать?').fill('Решить пять заданий');
  await page.getByLabel('Регулярность').selectOption('daily');
  await page.getByLabel('Плановая длительность, минут').fill('20');
  await page.getByRole('button',{name:'Добавить задачу',exact:true}).last().click();
  await expect(page.locator('.task-title').first()).toHaveText('Решить пять заданий');
  await page.locator('[data-complete]').first().check();
  await expect(page.locator('.wallet')).toContainText('5');
  await page.locator('[data-complete]').first().uncheck();
  await expect(page.locator('.wallet')).toContainText('0');
  await page.locator('[data-complete]').first().check();
  await expect(page.locator('.wallet')).toContainText('5');
  await page.reload();
  await expect(page.getByRole('heading',{name:'Подготовиться к пробнику',exact:true})).toBeVisible();
  await expect(page.locator('.wallet')).toContainText('5');
});
